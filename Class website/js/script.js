/* =========================
   MEMORY RENDERING
========================= */

const memoryGrid =
    document.getElementById("memoryGrid");


let currentMemories = [
    ...memoriesData
];


let currentMemoryIndex = 0;


function renderMemories(data) {

    memoryGrid.innerHTML = "";


    data.forEach((memory, index) => {

        const card =
            document.createElement("div");

        card.className = "memory";


        card.innerHTML = `

            <img
                src="${memory.image}"
                alt="${memory.title}"
                loading="lazy"
            >

            <div class="memory-overlay">

                <span>
                    MEMORY #${String(memory.id).padStart(2, "0")}
                </span>

                <strong>
                    ${memory.title}
                </strong>

            </div>

        `;


        card.addEventListener(
            "click",
            () => {

                openMemory(index);

            }
        );


        memoryGrid.appendChild(card);

    });

}


renderMemories(currentMemories);

/* =========================
   MEMORY FILTER
========================= */

const memoryFilters =
    document.querySelectorAll(
        ".memory-filter"
    );


memoryFilters.forEach(filter => {

    filter.addEventListener(
        "click",
        () => {

            memoryFilters.forEach(button => {

                button.classList.remove(
                    "active"
                );

            });


            filter.classList.add(
                "active"
            );


            const category =
                filter.dataset.filter;


            if (category === "all") {

                currentMemories = [
                    ...memoriesData
                ];

            } else {

                currentMemories =
                    memoriesData.filter(
                        memory =>
                            memory.category === category
                    );

            }


            renderMemories(
                currentMemories
            );

        }
    );

});



/* =========================
   MEMORY LIGHTBOX
========================= */

const memoryLightbox =
    document.getElementById(
        "memoryLightbox"
    );


const memoryClose =
    document.getElementById(
        "memoryClose"
    );


const memoryPrev =
    document.getElementById(
        "memoryPrev"
    );


const memoryNext =
    document.getElementById(
        "memoryNext"
    );


const lightboxImage =
    document.getElementById(
        "lightboxImage"
    );


const lightboxNumber =
    document.getElementById(
        "lightboxNumber"
    );


const lightboxTitle =
    document.getElementById(
        "lightboxTitle"
    );


const lightboxDescription =
    document.getElementById(
        "lightboxDescription"
    );


const lightboxDate =
    document.getElementById(
        "lightboxDate"
    );


function openMemory(index) {

    if (
        !currentMemories.length
    ) return;


    currentMemoryIndex = index;


    updateLightbox();


    memoryLightbox.classList.add(
        "show"
    );


    document.body.classList.add(
        "modal-open"
    );

}


function updateLightbox() {

    const memory =
        currentMemories[
            currentMemoryIndex
        ];


    lightboxImage.src =
        memory.image;


    lightboxImage.alt =
        memory.title;


    lightboxNumber.textContent =
        `MEMORY #${String(memory.id).padStart(2, "0")}`;


    lightboxTitle.textContent =
        memory.title;


    lightboxDescription.textContent =
        memory.description;


    lightboxDate.textContent =
        memory.date;

}


function closeMemory() {

    memoryLightbox.classList.remove(
        "show"
    );


    document.body.classList.remove(
        "modal-open"
    );

}


function nextMemory() {

    currentMemoryIndex++;

    if (
        currentMemoryIndex >=
        currentMemories.length
    ) {

        currentMemoryIndex = 0;

    }


    updateLightbox();

}


function previousMemory() {

    currentMemoryIndex--;

    if (
        currentMemoryIndex < 0
    ) {

        currentMemoryIndex =
            currentMemories.length - 1;

    }


    updateLightbox();

}


memoryClose.addEventListener(
    "click",
    closeMemory
);


memoryNext.addEventListener(
    "click",
    nextMemory
);


memoryPrev.addEventListener(
    "click",
    previousMemory
);


memoryLightbox.addEventListener(
    "click",
    event => {

        if (
            event.target ===
            memoryLightbox
        ) {

            closeMemory();

        }

    }
);


/* KEYBOARD */

document.addEventListener(
    "keydown",
    event => {

        if (
            !memoryLightbox.classList.contains(
                "show"
            )
        ) return;


        if (event.key === "Escape") {

            closeMemory();

        }


        if (event.key === "ArrowRight") {

            nextMemory();

        }


        if (event.key === "ArrowLeft") {

            previousMemory();

        }

    }
);


